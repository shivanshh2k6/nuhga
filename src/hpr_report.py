import io
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

def generate_hpr_pdf(plot_id: str, applicant: str, screening_result: dict, reviewer_status: str = "Pending Official Review") -> bytes:
    """Generate a downloadable PDF Hydrological Pre-Scrutiny Report (HPR)."""
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4

    ref_id = f"HPR-BPL-{datetime.now().strftime('%Y%m%d-%H%M%S')}"

    # Header Banner
    c.setFillColorRGB(0.06, 0.09, 0.16)
    c.rect(0, height - 85, width, 85, fill=1, stroke=0)
    c.setFillColorRGB(1, 1, 1)
    c.setFont("Helvetica-Bold", 15)
    c.drawString(40, height - 40, "NUHGA 2.0: HYDROLOGICAL PRE-SCRUTINY REPORT (HPR)")
    c.setFont("Helvetica", 9.5)
    c.drawString(40, height - 58, "Pilot Area: Shahpura Lake Urban Catchment, Bhopal (MP) | Decision-Support Prototype")
    c.drawString(40, height - 72, f"Report Reference ID: {ref_id}   |   Generated: {datetime.now().strftime('%Y-%m-%d %H:%M IST')}")

    y = height - 115
    c.setFillColorRGB(0.1, 0.1, 0.1)

    # Section 1: Application Details
    c.setFont("Helvetica-Bold", 11)
    c.drawString(40, y, "1. Plot & Application Metadata")
    y -= 18
    c.setFont("Helvetica", 10)
    c.drawString(50, y, f"Plot Identifier: {plot_id}")
    y -= 15
    c.drawString(50, y, f"Applicant / Scenario: {applicant}")
    y -= 15
    c.drawString(50, y, f"Site Drainage Plan Submitted: {'Yes' if screening_result.get('submitted_drainage_plan') else 'No'}")
    y -= 25

    # Section 2: Screening Status
    c.setFont("Helvetica-Bold", 11)
    c.drawString(40, y, "2. Automated GIS & Hydrological Screening Outcome")
    y -= 18
    c.setFont("Helvetica-Bold", 10.5)
    status_str = screening_result.get("status", "UNKNOWN")
    if status_str == "REVIEW_REQUIRED":
        c.setFillColorRGB(0.75, 0.1, 0.1)
    elif status_str == "NO_MAPPED_CONFLICT_IDENTIFIED":
        c.setFillColorRGB(0.05, 0.5, 0.25)
    else:
        c.setFillColorRGB(0.7, 0.45, 0.0)
    c.drawString(50, y, f"Preliminary Screening Status: {status_str}")
    c.setFillColorRGB(0.1, 0.1, 0.1)
    y -= 18

    c.setFont("Helvetica", 10)
    c.drawString(50, y, f"- Direct Water-Body Overlaps: {screening_result.get('water_body_conflicts', 0)}")
    y -= 15
    c.drawString(50, y, f"- Drainage Corridor Overlaps: {screening_result.get('drainage_conflicts', 0)}")
    y -= 15
    c.drawString(50, y, f"- Protective Buffer Warnings: {screening_result.get('buffer_warnings', 0)}")
    y -= 25

    # Section 3: Detailed Findings
    c.setFont("Helvetica-Bold", 11)
    c.drawString(40, y, "3. Evidence-Linked Spatial Findings")
    y -= 18
    c.setFont("Helvetica", 9.5)
    for finding in screening_result.get("findings", []):
        c.drawString(50, y, f"* {finding[:95]}")
        if len(finding) > 95:
            y -= 13
            c.drawString(60, y, finding[95:190])
        y -= 16

    y -= 10
    # Section 4: Data Provenance & Municipal Review Record
    c.setFont("Helvetica-Bold", 11)
    c.drawString(40, y, "4. Data Layers Audited & Municipal Review Status")
    y -= 18
    c.setFont("Helvetica", 9.5)
    c.drawString(50, y, "Layers Checked: Shahpura Lake Wetland Layer (2025-11), Drainage Corridors (2025-06), Sentinel-2 AI Flags (2026-02)")
    y -= 15
    c.drawString(50, y, f"Current Municipal Officer Review Status: {reviewer_status}")
    y -= 30

    # Mandatory Legal Disclaimer Box
    c.setStrokeColorRGB(0.7, 0.1, 0.1)
    c.setFillColorRGB(0.99, 0.95, 0.95)
    c.rect(40, y - 55, width - 80, 65, fill=1, stroke=1)
    c.setFillColorRGB(0.5, 0.05, 0.05)
    c.setFont("Helvetica-Bold", 9.5)
    c.drawString(50, y - 12, "IMPORTANT LEGAL & TECHNICAL LIMITATION NOTICE:")
    c.setFont("Helvetica", 8.5)
    c.drawString(50, y - 26, "This Hydrological Pre-Scrutiny Report (HPR) is a preliminary decision-support output generated by the NUHGA prototype.")
    c.drawString(50, y - 38, "It is NOT an official construction permit or legal clearance, nor does it guarantee a plot is free of flood risk.")
    c.drawString(50, y - 50, "All spatial flags must be verified against certified revenue/municipal records and site inspection by the competent authority.")

    c.showPage()
    c.save()
    buffer.seek(0)
    return buffer.getvalue()